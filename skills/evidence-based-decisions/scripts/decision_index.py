"""decision_index.py [DIR] [--check] — regenerate a decision log's README index from its entries.

The index is the `| Id | Title | Status |` table: one row per `NNNN-…md` entry in filename order,
the title from its `# D-NNN — Title` line, the status from its `**Status:**` line without bold or
date (`Accepted`, `Proposed`, `Open`, `SUPERSEDED by D-028`). Text before and after the table is
kept; a log with no README gets one. `--check` writes nothing and exits 1 if the README is stale.
Standard library only.
"""

import argparse
import os
import re
import sys

ENTRY = re.compile(r"^(\d{4}[a-z]?)-.+\.md$")
TITLE = re.compile(r"^# (D-\d{3,}[a-z]?) — (.+?)\s*$")
STATUS = re.compile(r"^\*\*Status:\*\*\s*(.+)$", re.M)
HEADER = "| Id | Title | Status |"
NEW_README = ("# Decision log\n\nWhy this project is the way it is, and what was given up: one decision per\n"
              "file. This index is generated by `decision_index.py`; reasoning lives in the entries.\n\n")


def rows(folder: str) -> tuple[list[str], list[str]]:
    out, errors = [], []
    for name in sorted(n for n in os.listdir(folder) if ENTRY.match(n)):
        text = open(os.path.join(folder, name), encoding="utf-8").read()
        title = TITLE.match(text.splitlines()[0] if text else "")
        status = STATUS.search(text)
        if not title or not status:
            errors.append(f"{name}: needs a `# D-NNN — Title` first line and a `**Status:**` line")
            continue
        line = status.group(1).replace("*", "")
        state = re.split(r"[(.]", line, maxsplit=1)[0].strip()
        replaced = re.search(r"\bSupersedes ((?:D-\d{3,}[a-z]?(?:, )?)+)", line)
        if replaced:
            state += f", supersedes {replaced.group(1).rstrip(', ')}"
        num = ENTRY.match(name).group(1)
        out.append(f"| [D-{int(num[:4]):03d}{num[4:]}]({name}) | {title.group(2)} | {state} |")
    return out, errors


def render(readme: str, table: list[str]) -> str:
    lines = readme.split("\n")
    start = next((i for i, line in enumerate(lines) if line.strip() == HEADER), None)
    if start is None:
        body = readme.rstrip("\n")
        return (body + "\n\n" if body else NEW_README) + "\n".join(table) + "\n"
    end = start + 1
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    return "\n".join(lines[:start] + table + lines[end:])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("dir", nargs="?", default=os.path.join("docs", "decisions"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    entries, errors = rows(a.dir) if os.path.isdir(a.dir) else ([], [])
    for e in errors:
        print(f"ERROR {e}")
    if errors:
        sys.exit(1)
    path = os.path.join(a.dir, "README.md")
    raw = open(path, "rb").read() if os.path.exists(path) else b""
    crlf = b"\r\n" in raw
    old = raw.decode("utf-8").replace("\r\n", "\n")
    new = render(old, [HEADER, "| --- | --- | --- |", *entries])
    if a.check:
        print("index is current" if new == old else f"{path} is stale: run decision_index.py")
        sys.exit(0 if new == old else 1)
    if new != old:
        os.makedirs(a.dir, exist_ok=True)
        with open(path, "wb") as f:
            f.write((new.replace("\n", "\r\n") if crlf else new).encode("utf-8"))
    print(f"{path}: {len(entries)} entries")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")  # readers decode UTF-8, whatever the console uses
    main()
